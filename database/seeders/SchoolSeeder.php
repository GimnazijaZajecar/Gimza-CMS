    public function run(): void
    {
        $this->seedClasses();
        $subjects = $this->seedSubjects();
        $this->seedStaff($subjects);
    }

    /**
     * Шеснаест одељења: I-1 до IV-4 (страница „Распоред часова“).
     */
    protected function seedClasses(): void
    {
        foreach ([1, 2, 3, 4] as $grade) {
            foreach ([1, 2, 3, 4] as $section) {
                SchoolClass::create(['grade' => $grade, 'section' => $section]);
            }
        }
    }

    /**
     * Сви предмети које предају запослени са странице „Колектив“.
     *
     * @return array<string, Subject>
     */
    protected function seedSubjects(): array
    {
        $names = collect(self::STAFF)
            ->except('Администрација')
            ->flatMap(fn (array $group) => collect($group['people'])->flatten())
            ->unique()
            ->sort()
            ->values();

        return $names->mapWithKeys(fn (string $name) => [$name => Subject::create(['name' => $name])])->all();
    }

    /**
     * Налози за запослене (улога „професор“). Лозинка је иста као за администратора.
     *
     * @param  array<string, Subject>  $subjects
     */
    protected function seedStaff(array $subjects): void
    {
        $password = DatabaseSeeder::$password;

        foreach (self::STAFF as $group => $data) {
            foreach ($data['people'] as $fullName => $items) {
                [$firstName, $lastName] = explode(' ', $fullName, 2);

                // Код администрације је звање уписано уместо предмета.
                $title = $group === 'Администрација' ? $items[0] : $data['title'];
                $subjectNames = $group === 'Администрација' ? [] : $items;

                $username = Slug::make($fullName, '.');

                $user = User::create([
                    'first_name' => $firstName,
                    'last_name' => $lastName,
                    'title' => $title,
                    'username' => $username,
                    'email' => "{$username}@gimza.test",
                    'password' => $password,
                    'role' => UserRole::Profesor,
                    'is_active' => true,
                    'email_verified_at' => now(),
                ]);

                $user->subjects()->attach(collect($subjectNames)->map(fn (string $name) => $subjects[$name]->id));
            }
        }
    }
